// Turns the AFCD (Australian Food Composition Database, Food Standards Australia New Zealand)
// "Nutrient profiles" spreadsheet into a migration that fills public.reference_foods (spec 007).
//
//   node scripts/afcd/build-seed.mjs <output.sql> [data-directory]
//
// The downloaded .xlsx files live in scripts/afcd/data/ (git-ignored); only the SQL is committed.
// Foods that are liquids appear on a second sheet per 100 mL, and use that row (unit ml) so a
// "250 ml" portion scales correctly. Everything else is per 100 g.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import readXlsxFile from "read-excel-file/node";
import { kilojoulesToCalories } from "../../src/lib/energy.ts";

const [output, directory = "scripts/afcd/data"] = process.argv.slice(2);
if (!output) {
  console.error(
    "Usage: node scripts/afcd/build-seed.mjs <output.sql> [data-directory]",
  );
  process.exit(1);
}

const SOURCE = "AFCD";
const FILE = "AFCD Release 3 - Nutrient profiles.xlsx";
const SOLIDS_SHEET = "All solids & liquids per 100 g";
const LIQUIDS_SHEET = "Liquids only per 100 mL";
const ENERGY_HEADER = /^Energy with dietary fibre, equated/;

const sheets = await readXlsxFile(join(directory, FILE));

// The header row is the one whose first cell is "Public Food Key".
function readFoods(name, unit) {
  const sheet = sheets.find((s) => s.sheet === name);
  if (!sheet) throw new Error(`The sheet "${name}" is not in ${FILE}`);
  const headerAt = sheet.data.findIndex((row) => row[0] === "Public Food Key");
  if (headerAt < 0) throw new Error(`No header row in "${name}"`);
  const header = sheet.data[headerAt];
  const keyAt = header.indexOf("Public Food Key");
  const nameAt = header.indexOf("Food Name");
  const energyAt = header.findIndex((cell) => ENERGY_HEADER.test(String(cell)));
  if (nameAt < 0 || energyAt < 0)
    throw new Error(`Missing columns in "${name}"`);
  return sheet.data.slice(headerAt + 1).flatMap((row) => {
    const key = row[keyAt];
    if (!key) return [];
    return [
      {
        key: String(key).trim(),
        name: String(row[nameAt] ?? "").trim(),
        kj: row[energyAt],
        unit,
      },
    ];
  });
}

const liquids = readFoods(LIQUIDS_SHEET, "ml");
const liquidKeys = new Set(liquids.map((food) => food.key));
const solids = readFoods(SOLIDS_SHEET, "g").filter(
  (food) => !liquidKeys.has(food.key),
);

const rows = [];
const skipped = [];
for (const food of [...solids, ...liquids]) {
  const kj = typeof food.kj === "number" ? food.kj : Number.NaN;
  if (!food.name || !Number.isFinite(kj) || kj < 0) {
    skipped.push(`${food.key} ${food.name}`);
    continue;
  }
  const calories = kilojoulesToCalories(kj);
  if (calories > 9999 || food.name.length > 200) {
    skipped.push(`${food.key} ${food.name}`);
    continue;
  }
  rows.push({ ...food, kj: Math.round(kj * 10) / 10, calories });
}
rows.sort((a, b) => a.key.localeCompare(b.key));

const quote = (text) => `'${text.replaceAll("'", "''")}'`;
const values = rows
  .map(
    (r) =>
      `  (${quote(SOURCE)}, ${quote(r.key)}, ${quote(r.name)}, ${r.kj}, ${r.calories}, ${quote(r.unit)})`,
  )
  .join(",\n");

const sql = `-- Reference Foods from the Australian Food Composition Database, Release 3 (spec 007).
-- Generated by scripts/afcd/build-seed.mjs from the FSANZ "Nutrient profiles" file; do not edit by hand.
-- Energy is "Energy with dietary fibre, equated" in kJ; Calories are converted and rounded half-up.
-- Source: Food Standards Australia New Zealand, Australian Food Composition Database.

insert into public.reference_foods (source, source_id, name, energy_kj_per_100, calories_per_100, unit)
values
${values}
on conflict (source, source_id) do nothing;
`;

writeFileSync(output, sql);
console.log(
  `${rows.length} foods written to ${output} (${solids.length} per 100 g, ${liquids.length} per 100 mL); ${skipped.length} skipped`,
);
for (const line of skipped) console.log(`  skipped: ${line}`);
