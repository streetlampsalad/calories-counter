// Pure rules for in-app Bug reports (specs/194-bug-reports/): which Bug Issues came from the app,
// which outcome each one is at, and the update the app is sent. Like the Feature Request sync, a
// projection: re-running it always gives the same answer.
import { pullRefs } from "./board.mjs";
import { requestedBy } from "./feature-requests.mjs";

const REVIEW = "needs-human-review";
const CLAIM = "Claimed by /deliver";
const TITLE_MAX = 256;
const COMMENT_MAX = 2000;
const DAYS_MS = 30 * 24 * 60 * 60 * 1000;

/** The Bug report id under a Bug's `### Requested by`, or null for a Bug filed on GitHub. */
export const isInAppBug = (body) => requestedBy(body) !== null;

/**
 * The outcome a Bug is at (US3.2).
 * @param {{ state: string, stateReason: string | null, labels: string[], pullLabels: string[][] }} facts
 *   `pullLabels` is the labels of each open pull request that refers to the Bug.
 */
export function outcomeFor({ state, stateReason, labels, pullLabels }) {
  if (state === "closed")
    return stateReason === "completed" ? "fixed" : "not_going_ahead";
  if (labels.includes(REVIEW) || pullLabels.some((l) => l.includes(REVIEW)))
    return "waiting_for_owner";
  if (labels.includes("needs-triage")) return "sent";
  return "being_fixed";
}

// The attribution line agents add to a comment is not the reason.
const FOOTER = /\s*---\s*\r?\n_Generated by \[Claude Code\][\s\S]*$/;

/** The newest comment that says something, without the attribution footer, for the User to read. */
export function latestReason(comments) {
  const newest = [...comments].sort((a, b) =>
    b.created_at.localeCompare(a.created_at),
  );
  for (const comment of newest) {
    if (comment.body.trim().startsWith(CLAIM)) continue;
    const text = comment.body.replace(FOOTER, "").trim();
    if (text) return text.slice(0, COMMENT_MAX);
  }
  return null;
}

/**
 * The updates to send: every in-app Bug that is open or was closed in the last 30 days.
 * `commentsFor(number)` reads an Issue's comments; it is only called for Bugs that are sent.
 */
export function bugReportUpdates({
  issues,
  pulls,
  commentsFor,
  now = new Date(),
}) {
  const since = now.getTime() - DAYS_MS;
  const openPulls = pulls.map((pull) => ({
    refs: pullRefs(pull),
    labels: pull.labels.map((label) => label.name),
  }));

  const updates = [];
  for (const issue of issues) {
    const id = issue.pull_request ? null : requestedBy(issue.body);
    if (!id) continue;
    if (issue.state === "closed" && new Date(issue.closed_at).getTime() < since)
      continue;
    updates.push({
      id,
      bug_issue: issue.number,
      outcome: outcomeFor({
        state: issue.state,
        stateReason: issue.state_reason ?? null,
        labels: issue.labels.map((label) => label.name),
        pullLabels: openPulls
          .filter((pull) => pull.refs.includes(issue.number))
          .map((pull) => pull.labels),
      }),
      issue_title: issue.title.slice(0, TITLE_MAX),
      latest_comment: latestReason(commentsFor(issue.number)),
    });
  }
  return updates;
}

/**
 * Posts the updates to the app. Skips with a warning while the app is not set up for it yet (no
 * secret or address, or the route not deployed), so the board never fails in that gap.
 */
export async function sendBugReportSync({
  url,
  secret,
  updates,
  fetchImpl = fetch,
  warn = (message) => console.log(`::warning::${message}`),
}) {
  if (!secret || !url) {
    warn(
      "FEATURE_REQUESTS_SYNC_SECRET or PRODUCTION_URL is not set, so Bug reports were not synced. Run scripts/setup-feature-requests.sh.",
    );
    return "skipped";
  }
  const response = await fetchImpl(`${url}/api/bug-reports/sync`, {
    method: "POST",
    headers: { "content-type": "application/json", "x-sync-secret": secret },
    body: JSON.stringify({ updates }),
    signal: AbortSignal.timeout(30_000),
  });
  if (response.status === 404) {
    warn("The app has no Bug reports sync route yet, so nothing was synced.");
    return "skipped";
  }
  if (!response.ok)
    throw new Error(
      `The app answered ${response.status} to the Bug reports sync`,
    );
  return "sent";
}
