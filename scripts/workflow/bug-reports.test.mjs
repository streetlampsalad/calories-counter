import { describe, expect, it } from "vitest";
import {
  bugReportUpdates,
  isInAppBug,
  latestReason,
  outcomeFor,
} from "./bug-reports.mjs";

// The outcome rules for in-app Bug reports (spec 194 US3.2, US3.3).

const ID = "11111111-2222-4333-8444-555555555555";
const NOW = new Date("2026-11-11T00:00:00Z");
const inApp = `### Actual\n\n> It broke\n\n### Requested by\n\n${ID}\n\n### Risk assessment\n\n- [ ] x`;

const bug = (overrides = {}) => ({
  number: 300,
  title: "Bug: it broke",
  body: inApp,
  state: "open",
  state_reason: null,
  closed_at: null,
  labels: [{ name: "bug" }, { name: "needs-triage" }],
  ...overrides,
});
const pull = (overrides = {}) => ({
  number: 400,
  title: "Fix it",
  body: "Refs #300",
  labels: [{ name: "needs-human-review" }],
  ...overrides,
});
const facts = (issue, pulls = []) => ({
  state: issue.state,
  stateReason: issue.state_reason,
  labels: issue.labels.map((l) => l.name),
  pullLabels: pulls.map((p) => p.labels.map((l) => l.name)),
});

describe("isInAppBug", () => {
  it("needs a Requested by with a UUID", () => {
    expect(isInAppBug(inApp)).toBe(true);
    expect(isInAppBug("### Requested by\n\nsomeone")).toBe(false);
    expect(isInAppBug("### Requested by\n\n")).toBe(false);
    expect(isInAppBug(null)).toBe(false);
  });
});

describe("outcomeFor", () => {
  it("is Sent while it is labelled needs-triage", () => {
    expect(outcomeFor(facts(bug()))).toBe("sent");
  });

  it("is Being fixed once needs-triage is gone", () => {
    expect(
      outcomeFor(
        facts(bug({ labels: [{ name: "bug" }, { name: "priority:P1" }] })),
      ),
    ).toBe("being_fixed");
  });

  it("is Waiting for the owner with needs-human-review on the Bug", () => {
    expect(
      outcomeFor(facts(bug({ labels: [{ name: "needs-human-review" }] }))),
    ).toBe("waiting_for_owner");
  });

  it("is Waiting for the owner with needs-human-review on an open pull request", () => {
    expect(outcomeFor(facts(bug({ labels: [] }), [pull()]))).toBe(
      "waiting_for_owner",
    );
  });

  it("is Fixed when closed as completed, and Not going ahead when closed otherwise", () => {
    expect(
      outcomeFor(facts(bug({ state: "closed", state_reason: "completed" }))),
    ).toBe("fixed");
    expect(
      outcomeFor(facts(bug({ state: "closed", state_reason: "not_planned" }))),
    ).toBe("not_going_ahead");
    expect(
      outcomeFor(facts(bug({ state: "closed", state_reason: null }))),
    ).toBe("not_going_ahead");
  });

  it("puts closed before any label", () => {
    expect(
      outcomeFor(
        facts(
          bug({
            state: "closed",
            state_reason: "completed",
            labels: [{ name: "needs-human-review" }, { name: "needs-triage" }],
          }),
        ),
      ),
    ).toBe("fixed");
  });
});

describe("latestReason", () => {
  const footer =
    "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";

  it("is the newest comment without the attribution footer", () => {
    expect(
      latestReason([
        { body: "Older", created_at: "2026-11-01T00:00:00Z" },
        {
          body: `It works as designed.${footer}`,
          created_at: "2026-11-05T00:00:00Z",
        },
      ]),
    ).toBe("It works as designed.");
  });

  it("is null with no comments, and cuts to 2,000 characters", () => {
    expect(latestReason([])).toBeNull();
    expect(
      latestReason([
        { body: "a".repeat(3000), created_at: "2026-11-01T00:00:00Z" },
      ]),
    ).toHaveLength(2000);
  });
});

describe("bugReportUpdates", () => {
  const comments = {
    300: [{ body: "Why not", created_at: "2026-11-02T00:00:00Z" }],
  };
  const run = (issues, pulls = []) =>
    bugReportUpdates({
      issues,
      pulls,
      commentsFor: (number) => comments[number] ?? [],
      now: NOW,
    });

  it("sends the id, number, outcome, title and latest comment of an in-app Bug", () => {
    expect(
      run([
        bug({
          state: "closed",
          state_reason: "not_planned",
          closed_at: "2026-11-02T00:00:00Z",
        }),
      ]),
    ).toEqual([
      {
        id: ID,
        bug_issue: 300,
        outcome: "not_going_ahead",
        issue_title: "Bug: it broke",
        latest_comment: "Why not",
      },
    ]);
  });

  it("skips Bugs filed on GitHub and pull requests", () => {
    expect(
      run([
        bug({ body: "### Requested by\n\n" }),
        bug({ number: 301, pull_request: {} }),
      ]),
    ).toEqual([]);
  });

  it("skips Bugs closed more than 30 days ago", () => {
    expect(
      run([
        bug({
          state: "closed",
          state_reason: "completed",
          closed_at: "2026-09-01T00:00:00Z",
        }),
      ]),
    ).toEqual([]);
  });

  it("cuts the title to 256 characters and uses the pull requests that refer to the Bug", () => {
    const [update] = run(
      [bug({ title: "t".repeat(300), labels: [] })],
      [pull(), pull({ number: 401, body: "Refs #999" })],
    );
    expect(update.issue_title).toHaveLength(256);
    expect(update.outcome).toBe("waiting_for_owner");
    expect(
      run([bug({ labels: [] })], [pull({ body: "Refs #999" })])[0].outcome,
    ).toBe("being_fixed");
  });
});

describe("sendBugReportSync", () => {
  const send = (options) =>
    import("./bug-reports.mjs").then((m) =>
      m.sendBugReportSync({ updates: [], warn: () => {}, ...options }),
    );

  it("skips without a secret or address", async () => {
    expect(await send({ url: "https://x.test", secret: "" })).toBe("skipped");
  });

  it("posts the updates with the secret, and skips on a 404", async () => {
    const calls = [];
    const fetchImpl = async (url, init) => {
      calls.push({ url, init });
      return { status: 404, ok: false };
    };
    expect(await send({ url: "https://x.test", secret: "s", fetchImpl })).toBe(
      "skipped",
    );
    expect(calls[0].url).toBe("https://x.test/api/bug-reports/sync");
    expect(calls[0].init.headers["x-sync-secret"]).toBe("s");
    expect(JSON.parse(calls[0].init.body)).toEqual({ updates: [] });
  });

  it("throws on any other failure", async () => {
    await expect(
      send({
        url: "https://x.test",
        secret: "s",
        fetchImpl: async () => ({ status: 401, ok: false }),
      }),
    ).rejects.toThrow(/401/);
  });
});
